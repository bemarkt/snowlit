import CryptoKit
import Foundation
import SnowlitStorage

/// Owns temporary exports and isolated previews. It never changes the bootstrap
/// descriptor or opens a candidate as the active library.
actor BackupWorkspace {
    enum Failure: Error { case noPreparedBackup }
    private let openLibrary: @Sendable () async throws -> LibraryDatabase
    private let adoptDataset: @Sendable (PreparedLibraryBackup) async throws -> LibraryBackupSummary
    private let root: URL
    private var directories: [URL] = []
    private var prepared: PreparedLibraryBackup?
    private static let digest: LibraryBackup.Digest = { SHA256.hash(data: $0).map { String(format: "%02x", $0) }.joined() }

    init(openLibrary: @escaping @Sendable () async throws -> LibraryDatabase,
         adoptDataset: @escaping @Sendable (PreparedLibraryBackup) async throws -> LibraryBackupSummary) {
        self.openLibrary = openLibrary
        self.adoptDataset = adoptDataset
        root = FileManager.default.temporaryDirectory.appendingPathComponent("SnowlitBackup-\(UUID())")
    }

    func export(includeCache: Bool) async throws -> BackupModel.Export {
        let library = try await openLibrary()
        let folder = try prepare()
        let file = folder.appendingPathComponent("映雪备份.snowlitbackup")
        let summary = try await library.exportBackup(to: file, includeCache: includeCache, digest: Self.digest)
        return .init(file: file, summary: summary)
    }

    func preview(_ file: URL) async throws -> LibraryBackupSummary {
        let folder = try prepare()
        let scoped = file.startAccessingSecurityScopedResource()
        defer { if scoped { file.stopAccessingSecurityScopedResource() } }
        let prepared = try await LibraryBackup.preflight(file: file, into: folder.appendingPathComponent("candidate"), digest: Self.digest)
        self.prepared = prepared
        return prepared.summary
    }

    /// Adopts exactly the candidate that `preview` validated. The bootstrap owns
    /// the commit point; this workspace never reads a path from a backup.
    func adopt() async throws -> LibraryBackupSummary {
        guard let prepared else { throw Failure.noPreparedBackup }
        let summary = try await adoptDataset(prepared)
        self.prepared = nil
        // The adopted copy no longer needs the temporary preview. Reclaim it on
        // the next prepare/clear; a cleanup failure must not report a committed
        // restore as failed.
        return summary
    }

    func clear() throws {
        prepared = nil
        // Each path was generated by this instance, never decoded from a backup.
        while let directory = directories.last {
            if FileManager.default.fileExists(atPath: directory.path) { try FileManager.default.removeItem(at: directory) }
            directories.removeLast()
        }
        if FileManager.default.fileExists(atPath: root.path) { try FileManager.default.removeItem(at: root) }
    }

    private func prepare() throws -> URL {
        try Task.checkCancellation()
        try clear()
        try FileManager.default.createDirectory(at: root, withIntermediateDirectories: false)
        let directory = root.appendingPathComponent(UUID().uuidString)
        try FileManager.default.createDirectory(at: directory, withIntermediateDirectories: false)
        directories.append(directory)
        return directory
    }
}
